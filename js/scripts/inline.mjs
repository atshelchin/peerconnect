// Writes the WebAssembly module as a base64 string export.
import { readFileSync, writeFileSync } from "node:fs";
const [wasm, out] = process.argv.slice(2);
const base64 = readFileSync(wasm).toString("base64");
writeFileSync(out, `// Generated by scripts/inline.mjs.\nexport default "${base64}";\n`);
